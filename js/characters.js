// Получить случайную фразу персонажа
function getCharacterPhrase(character, type) {
  if (type === "correct") {
    const phrases = character.successPhrases;
    return phrases[Math.floor(Math.random() * phrases.length)];
  }
  if (type === "wrong") {
    const phrases = character.failPhrases;
    return phrases[Math.floor(Math.random() * phrases.length)];
  }
  return "";
}

// Найти персонажа по зоне
function getCharacterByZone(zone) {
  return CHARACTERS.find(c => c.zone === zone) || CHARACTERS[0];
}

// Найти персонажа по id
function getCharacterById(id) {
  return CHARACTERS.find(c => c.id === id) || CHARACTERS[0];
}
